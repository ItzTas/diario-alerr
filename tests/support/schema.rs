use tokio_postgres::Client;

const GOOSE_FILES: [(i64, &str); 2] = [
    (1, include_str!("../../sql/schema/00001_monitor.sql")),
    (2, include_str!("../../sql/schema/00002_acked_seq.sql")),
];

const GOOSE_TABLE: &str = "CREATE TABLE goose_db_version (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id bigint NOT NULL,
    is_applied boolean NOT NULL,
    tstamp timestamp NOT NULL DEFAULT now()
)";
const RECORD_GOOSE_VERSION: &str =
    "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)";

const COLUMNS: &str = "SELECT json_build_array(table_name, column_name, data_type, is_nullable,
    column_default, is_identity, identity_generation)::text
FROM information_schema.columns
WHERE table_schema = current_schema() AND table_name::text <> ALL($1::text[])";
const CONSTRAINTS: &str =
    "SELECT json_build_array(conrelid::regclass::text, conname, pg_get_constraintdef(oid))::text
FROM pg_constraint
WHERE connamespace = current_schema()::regnamespace
  AND conrelid <> 0
  AND conrelid::regclass::text <> ALL($1::text[])";
const INDEXES: &str = "SELECT indexdef FROM pg_indexes
WHERE schemaname = current_schema() AND tablename::text <> ALL($1::text[])";
const SEQUENCES: &str =
    "SELECT json_build_array(sequencename, data_type::text, start_value, increment_by)::text
FROM pg_sequences
WHERE schemaname = current_schema()";

